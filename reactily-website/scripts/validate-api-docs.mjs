const here = path.dirname(fileURLToPath(import.meta.url));
const apiRoot = path.resolve(here, "../src/content/api");

if (!fs.existsSync(apiRoot)) {
  console.error(`[validate:api] Missing API documentation directory: ${apiRoot}`);
  console.error("[validate:api] Expected project layout: reactily-website/src/content/api");
  console.error("[validate:api] If you see src/src locally, re-extract the package at the project root.");
  process.exit(1);
}

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(fullPath) : entry.name.endsWith(".md") ? [fullPath] : [];
  });
}

const documented = new Map();
for (const file of walk(apiRoot)) {
  const source = fs.readFileSync(file, "utf8");
  const match = /^title:\s*Reactily\.([A-Za-z_][A-Za-z0-9_]*)\s*$/m.exec(source);
  if (!match) continue;
  documented.set(match[1], file);
}

const missing = expected.filter((name) => !documented.has(name));
const stale = [...documented.keys()].filter((name) => !expected.includes(name));

if (missing.length || stale.length) {
  if (missing.length) console.error(`Missing Reactily API docs: ${missing.join(", ")}`);
  if (stale.length) console.error(`Stale Reactily API docs: ${stale.join(", ")}`);
  process.exit(1);
}

console.log(`Reactily API coverage OK: ${expected.length}/197 exports documented.`);
